"""Week 11: the fix measured against ground truth, per scenario family -- the "number that moved".

    python -m scripts.w11_family_eval            # writes coursework/w11/family_eval.md and family_eval.json

The suite's pass count mixes assertions with a noisy judge (Week 6 measured its agreement with human labels at 56%),
and it moved both ways on the same change. This script asks the question the drill actually raised -- *is the policy's
exclusion reflected in the decision?* -- against ground truth that does not depend on any judge:

* **excluded families** (the policy excludes the loss; an answer of ``covered`` is wrong): subsidence, regulatory fine,
  standing timber, stock below floor, construction over the threshold, cloud outage, ransom, second flood in the window.
* **covered families** (the wording covers the loss, usually via a carve-out or an unmet condition; an answer of
  ``denied`` is wrong): in-zone flood, stock raised above the floor, flood outside a zone, cyber write-back for fire,
  construction under the threshold, E-17 with the defence carve-out, business interruption past the waiting period.

Every family is run with ``carry_clause_stem`` off and on, over 8 seeds of the Week 5 scenario generator (the same
narrative with different claim numbers, dates and amounts). A fix that stops an exclusion being missed by making
the system deny everything would show up in the second group, which is why it is in the table.

The model is the offline stub (a deterministic reading-comprehension simulator), so these are measurements of the
*retrieval and context* change, not of how Claude or GPT would behave.
"""

from __future__ import annotations

import json
import random
import tempfile
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

from scripts.w5_scenarios import _build
from scripts.w11_traffic import EXCLUDED_FAMILIES, build_service

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "coursework" / "w11"
SEEDS = range(8)

#: families where the right answer is NOT "denied" (the wording covers the loss, possibly via a carve-out).
COVERED_FAMILIES = frozenset(
    {
        "flood_in_zone_covered",
        "stock_raised_covered",
        "flood_outside_zone",
        "cyber_fire_writeback",
        "construction_under_threshold",
        "e17_defence_carveout",
        "bi_past_waiting_period",
    }
)


def run(carry: bool) -> dict[str, Counter]:
    decisions: dict[str, Counter] = defaultdict(Counter)
    with tempfile.TemporaryDirectory() as tmp:
        service = build_service(Path(tmp), None, carry_clause_stem=carry)
        for seed in SEEDS:
            for scenario in _build(random.Random(seed)):
                if scenario.key in EXCLUDED_FAMILIES | COVERED_FAMILIES:
                    decisions[scenario.key][service.summarize_claim(scenario.notes).summary.coverage_decision] += 1
    return decisions


def wrong(family: str, counts: Counter) -> int:
    return counts["covered"] if family in EXCLUDED_FAMILIES else counts["denied"]


def main() -> None:
    before, after = run(False), run(True)
    rows: list[dict[str, Any]] = []
    lines = [
        "# Week 11 -- the fix measured against ground truth",
        "",
        "Generated by `python -m scripts.w11_family_eval`. Each family is the Week 5 scenario generator's narrative run over 8 seeds "
        "(different claim numbers, dates, amounts) through `summarize_claim`, with `carry_clause_stem` **off** (before) and **on** (after). "
        "Model: the offline stub, so this measures the retrieval/context change, not Claude or GPT.",
        "",
        "## Excluded families: an answer of `covered` is WRONG",
        "",
        "| family | n | wrong before | wrong after | decisions before -> after |",
        "|---|---|---|---|---|",
    ]

    def block(families: frozenset[str], heading_wrong: str) -> tuple[int, int, int]:
        total = wrong_b = wrong_a = 0
        for family in sorted(families):
            b, a = before[family], after[family]
            n = sum(b.values())
            rows.append({"family": family, "n": n, "wrong_before": wrong(family, b), "wrong_after": wrong(family, a), "before": dict(b), "after": dict(a)})
            lines.append(
                f"| {family} | {n} | {wrong(family, b)} ({wrong(family, b) / n:.0%}) | {wrong(family, a)} ({wrong(family, a) / n:.0%}) | "
                f"{dict(b)} -> {dict(a)} |"
            )
            total, wrong_b, wrong_a = total + n, wrong_b + wrong(family, b), wrong_a + wrong(family, a)
        lines.append(f"| **all** | **{total}** | **{wrong_b} ({wrong_b / total:.0%})** | **{wrong_a} ({wrong_a / total:.0%})** | |")
        return total, wrong_b, wrong_a

    ex_total, ex_before, ex_after = block(EXCLUDED_FAMILIES, "covered")
    lines += ["", "## Covered families: an answer of `denied` is WRONG (the over-blocking check)", "",
              "| family | n | wrong before | wrong after | decisions before -> after |", "|---|---|---|---|---|"]
    cv_total, cv_before, cv_after = block(COVERED_FAMILIES, "denied")
    lines += [
        "",
        "## Summary",
        "",
        f"- Excluded losses answered `covered` (the drill's complaint): **{ex_before}/{ex_total} ({ex_before / ex_total:.0%}) -> {ex_after}/{ex_total} ({ex_after / ex_total:.0%})**.",
        f"- Covered losses wrongly `denied` (over-blocking): **{cv_before}/{cv_total} ({cv_before / cv_total:.0%}) -> {cv_after}/{cv_total} ({cv_after / cv_total:.0%})**.",
        "",
    ]
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "family_eval.md").write_text("\n".join(lines), encoding="utf-8")
    (OUT_DIR / "family_eval.json").write_text(
        json.dumps({"seeds": list(SEEDS), "rows": rows, "excluded": [ex_total, ex_before, ex_after], "covered": [cv_total, cv_before, cv_after]}, indent=2),
        encoding="utf-8",
    )
    print("\n".join(lines))


if __name__ == "__main__":
    main()
